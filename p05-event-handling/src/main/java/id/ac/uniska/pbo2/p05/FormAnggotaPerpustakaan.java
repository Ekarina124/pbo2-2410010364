   /** Menampilkan jumlah digit NPM, misalnya "8 dari 10 digit". */
    private void perbaruiDigit() {
        int jumlah = npmField.getText().trim().length();
        digitLabel.setText(jumlah + " dari 10 digit");
    }

/** Mengosongkan semua isian lalu mengembalikan fokus ke NPM. */
    private void kosongkan() {
        npmField.setText("");
        namaField.setText("");
        prodiCombo.setSelectedIndex(0);
        mahasiswaRadio.setSelected(true);
        emailField.setText("");
        noHpField.setText("");
        alamatArea.setText("");
        setujuCheck.setSelected(false);
        perbaruiDigit();
        npmField.requestFocusInWindow();
    } 
    
