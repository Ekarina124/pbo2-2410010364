    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed
        String jenis = mahasiswaRadio.isSelected() ? "Mahasiswa"
                : dosenRadio.isSelected() ? "Dosen" : "Umum";
        // alamat bisa beberapa baris, baris lanjutan dijorokkan agar sejajar
        String alamat = alamatArea.getText().trim().replace("\n", "\n         ");

        javax.swing.JTextArea area = new javax.swing.JTextArea(
                "NPM    : " + npmField.getText().trim() + "\n"
                + "Nama   : " + namaField.getText().trim() + "\n"
                + "Prodi  : " + prodiCombo.getSelectedItem() + "\n"
                + "Jenis  : " + jenis + "\n"
                + "Email  : " + emailField.getText().trim() + "\n"
                + "No. HP : " + noHpField.getText().trim() + "\n"
                + "Alamat : " + alamat);
        area.setEditable(false);
        area.setOpaque(false);
        area.setFont(new java.awt.Font(java.awt.Font.MONOSPACED, java.awt.Font.PLAIN, 13));
        JOptionPane.showMessageDialog(this, area, "Ringkasan Pendaftaran",
                JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_daftarButtonActionPerformed

