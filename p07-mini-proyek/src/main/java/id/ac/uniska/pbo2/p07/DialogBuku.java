    private void simpan() {
        String kode = kodeField.getText().trim();
        String judul = judulField.getText().trim();
        String tahunTeks = tahunField.getText().trim();

        if (kode.isEmpty()) {
            pesanLabel.setText("Kode wajib diisi");
            kodeField.requestFocusInWindow();
            return;
        }
        if (kodeSudahAda.test(kode)) {
            pesanLabel.setText("Kode " + kode + " sudah dipakai buku lain");
            kodeField.requestFocusInWindow();
            return;
        }
        if (judul.isEmpty()) {
            pesanLabel.setText("Judul wajib diisi");
            judulField.requestFocusInWindow();
            return;
        }
        int tahunSekarang = Year.now().getValue();
        int tahun;
        try {
            tahun = Integer.parseInt(tahunTeks);
        } catch (NumberFormatException e) {
            pesanLabel.setText("Tahun terbit harus berupa angka");
            tahunField.requestFocusInWindow();
            return;
        }
        if (tahun < 1900 || tahun > tahunSekarang) {
            pesanLabel.setText("Tahun terbit antara 1900 dan " + tahunSekarang);
            tahunField.requestFocusInWindow();
            return;
        }
        StatusBuku status = (StatusBuku) statusCombo.getSelectedItem();
        hasil = new Buku(kode, judul, penulisField.getText().trim(), tahun, status);
        dispose();
    }

    /** Menampilkan dialog dan menunggu sampai ditutup. Mengembalikan null jika dibatalkan. */
    public Buku tampilkan() {
        setVisible(true);
        return hasil;
    }
    
