    public void tampilkanData(List<Buku> data) {
        model.setData(data);
        statusLabel.setText("Menampilkan " + data.size() + " buku");
        perbaruiTombol();
    }
    
    /** Buku pada baris yang dipilih, atau null jika belum ada yang dipilih. */
    public Buku getBukuTerpilih() {
        int baris = bukuTable.getSelectedRow();
        return baris < 0 ? null : model.get(bukuTable.convertRowIndexToModel(baris));
    }
    /** Membuka form buku. Mengembalikan null jika pengguna membatalkan. */
    public Buku tampilkanDialog(String judul, Buku awal) {
        return new DialogBuku(SwingUtilities.getWindowAncestor(this), judul, awal).tampilkan();
    }
    
    public void tampilkanInfo(String pesan) {
        statusLabel.setText(pesan);
    }
    
    public void tampilkanKesalahan(String pesan) {
        JOptionPane.showMessageDialog(this, pesan, "Tidak Dapat Diproses",
                JOptionPane.ERROR_MESSAGE);
    }
    
    public boolean konfirmasi(String pertanyaan) {
        return JOptionPane.showConfirmDialog(this, pertanyaan, "Konfirmasi",
                JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE) == JOptionPane.YES_OPTION;
    }
    
    private void perbaruiTombol() {        
        boolean adaPilihan = bukuTable.getSelectedRow() >= 0;
        ubahButton.setEnabled(adaPilihan);
        hapusButton.setEnabled(adaPilihan);
    }
    
    
